import ApplicationServices
import Cocoa

class ClipboardService {
    static let shared = ClipboardService()

    // Dependency injection for license checking
    private var licenseManager: LicenseManager {
        return LicenseManager.shared
    }

    private init() {}

    /// Pasteboard types other apps and clipboard managers use to skip temporary writes.
    /// See nspasteboard.org.
    fileprivate static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    fileprivate static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    private static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    /// Delay before putting the user's own clipboard back after an auto-paste.
    private static let restoreDelay: Duration = .milliseconds(500)
    /// Longest wait for the target app to come forward before pasting.
    private static let activationTimeout: TimeInterval = 0.2

    /// Every item on the pasteboard, with the raw data for each of its types.
    struct PasteboardSnapshot {
        fileprivate let items: [[(type: NSPasteboard.PasteboardType, data: Data)]]

        /// True when the previous contents were marked concealed or transient (e.g. a password
        /// manager copy). Those are never written back: restoring would re-publish the secret
        /// to clipboard history and defeat the password manager's own auto-clear.
        var isSensitive: Bool {
            items.contains { entries in
                entries.contains {
                    $0.type == ClipboardService.concealedType || $0.type == ClipboardService.transientType
                }
            }
        }
    }

    enum PasteResult {
        case pasted
        /// Accessibility is off: the text is on the clipboard for a manual ⌘V.
        case copiedOnly
    }

    /// Copy text to the system clipboard. `transient` marks the write so clipboard managers
    /// ignore it (used for auto-paste, where the user's clipboard is restored afterwards).
    /// Returns the pasteboard's change count after the write.
    @discardableResult
    func copy(text: String, transient: Bool = false) -> Int {
        let finalText = wrapTextIfNeeded(text)

        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()

        let item = NSPasteboardItem()
        item.setString(finalText, forType: .string)
        if transient {
            item.setData(Data(), forType: Self.transientType)
            item.setData(Data(), forType: Self.autoGeneratedType)
        }
        if !pasteboard.writeObjects([item]) {
            AppLogger.warning("Clipboard write failed", category: AppLogger.clipboard)
        }
        return pasteboard.changeCount
    }

    func snapshot() -> PasteboardSnapshot {
        let items = (NSPasteboard.general.pasteboardItems ?? []).map { item in
            item.types.compactMap { type in
                item.data(forType: type).map { (type: type, data: $0) }
            }
        }
        return PasteboardSnapshot(items: items)
    }

    func restore(_ snapshot: PasteboardSnapshot) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        let items = snapshot.items.compactMap { entries -> NSPasteboardItem? in
            guard !entries.isEmpty else { return nil }
            let item = NSPasteboardItem()
            for entry in entries {
                item.setData(entry.data, forType: entry.type)
            }
            return item
        }
        if !items.isEmpty {
            pasteboard.writeObjects(items)
        }
    }

    /// Put `text` into `target` (or the frontmost app) with a simulated ⌘V, then restore the
    /// user's previous clipboard. `beforePaste` runs right before focus moves (close panels there).
    /// Without Accessibility, nothing is pasted: the text stays on the clipboard for ⌘V.
    func pasteText(
        _ text: String,
        into target: NSRunningApplication?,
        beforePaste: () -> Void = {}
    ) async -> PasteResult {
        // Off the main thread: `AXIsProcessTrusted()` blocks on `tccd`.
        let trusted = await Task.detached(priority: .userInitiated) {
            AXIsProcessTrusted()
        }.value

        guard trusted else {
            copy(text: text)
            return .copiedOnly
        }

        let previous = snapshot()
        let ourChangeCount = copy(text: text, transient: true)

        beforePaste()
        await activate(target)
        paste()

        try? await Task.sleep(for: Self.restoreDelay)
        // Only restore if nothing else has written since our paste, and never restore secrets.
        if NSPasteboard.general.changeCount == ourChangeCount, !previous.isSensitive {
            restore(previous)
        }
        return .pasted
    }

    /// Bring `app` forward, waiting only as long as it takes (capped). No-op when it is
    /// already frontmost, which is the usual case since the recorder panel never activates.
    private func activate(_ app: NSRunningApplication?) async {
        guard let app, !app.isTerminated else { return }
        let isFrontmost = {
            NSWorkspace.shared.frontmostApplication?.processIdentifier == app.processIdentifier
        }
        guard !isFrontmost() else { return }

        app.activate()
        let deadline = Date().addingTimeInterval(Self.activationTimeout)
        while Date() < deadline {
            try? await Task.sleep(for: .milliseconds(20))
            if isFrontmost() { break }
        }
    }

    // Wrap text with promotional message for free users
    private func wrapTextIfNeeded(_ text: String) -> String {
        // License check disabled - always allow unwrapped text
        return text
    }

    // Paste content (Simulate Cmd+V)
    func paste() {
        // Create a concurrent task to avoid blocking main thread if needed,
        // though CGEvent is fast.
        DispatchQueue.main.async {
            let source = CGEventSource(stateID: .hidSystemState)

            // Command key down
            let cmdDown = CGEvent(keyboardEventSource: source, virtualKey: 0x37, keyDown: true)
            cmdDown?.flags = .maskCommand

            // 'V' key down
            let vDown = CGEvent(keyboardEventSource: source, virtualKey: 0x09, keyDown: true)
            vDown?.flags = .maskCommand

            // 'V' key up
            let vUp = CGEvent(keyboardEventSource: source, virtualKey: 0x09, keyDown: false)
            vUp?.flags = .maskCommand

            // Command key up
            let cmdUp = CGEvent(keyboardEventSource: source, virtualKey: 0x37, keyDown: false)

            // Post events
            cmdDown?.post(tap: .cghidEventTap)
            vDown?.post(tap: .cghidEventTap)
            vUp?.post(tap: .cghidEventTap)
            cmdUp?.post(tap: .cghidEventTap)

            print("Simulated Cmd+V")
        }
    }

    // Fallback using AppleScript (more robust for some apps)
    func appleScriptPaste() {
        let script = "tell application \"System Events\" to keystroke \"v\" using command down"
        if let appleScript = NSAppleScript(source: script) {
            var error: NSDictionary?
            appleScript.executeAndReturnError(&error)
            if let error = error {
                print("AppleScript Paste Error: \(error)")
            } else {
                print("Executed AppleScript Paste")
            }
        }
    }

    // Check if we have permission to send keystrokes
    /// Blocking `tccd` round-trip — never call this from the main thread.
    /// Prefer `PermissionService.shared.isAccessibilityGranted` for UI and hot paths.
    nonisolated var isAccessibilityTrusted: Bool {
        return AXIsProcessTrusted()
    }

    /// Request permission via the system prompt.
    /// Delegates to `PermissionService` so the blocking `tccd` call stays off the main
    /// thread and the dialog is brought to the front — calling
    /// `AXIsProcessTrustedWithOptions` directly here used to freeze the UI.
    func requestAccessibilityPermission() {
        Task { @MainActor in
            PermissionService.shared.requestAccessibilityPermission()
        }
    }
}
